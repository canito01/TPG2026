package persistencia.dao;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Centraliza la configuracion de conexion JDBC contra H2 y la inicializacion
 * idempotente del esquema de la tabla de usuarios.
 */
public class ConexionBD {

    public static final String URL_POR_DEFECTO = "jdbc:h2:./data/tpg2026";
    public static final String USUARIO_POR_DEFECTO = "sa";
    public static final String PASSWORD_POR_DEFECTO = "";

    private static final String DDL_USUARIOS =
            "CREATE TABLE IF NOT EXISTS usuarios (" +
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
            "nombre_usuario VARCHAR(50) NOT NULL UNIQUE, " +
            "password_hash VARCHAR(255) NOT NULL, " +
            "fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP" +
            ")";

    private final String url;
    private final String usuario;
    private final String password;

    public ConexionBD() {
        this(URL_POR_DEFECTO, USUARIO_POR_DEFECTO, PASSWORD_POR_DEFECTO);
    }

    public ConexionBD(String url, String usuario, String password) {
        if (url == null || url.isBlank()) {
            throw new IllegalArgumentException("La URL JDBC no puede ser vacia.");
        }
        this.url = url;
        this.usuario = usuario != null ? usuario : "";
        this.password = password != null ? password : "";
    }

    public Connection obtenerConexion() throws SQLException {
        return DriverManager.getConnection(url, usuario, password);
    }

    public void inicializarEsquema() {
        try (Connection conn = obtenerConexion();
             Statement stmt = conn.createStatement()) {
            stmt.execute(DDL_USUARIOS);
        } catch (SQLException e) {
            throw new PersistenciaException("Error al inicializar el esquema de la base de datos.", e);
        }
    }
}
